test('独立方向、统一下一步、保留焦点、阅读辅助与空态', async ({ page, browser }, testInfo) => {
  const evidence = testInfo.outputPath('evidence');
  test.setTimeout(120_000);
  await mkdir(evidence, {recursive:true});
  await page.request.post('/api/v1/import/reset-learning-progress', {data:{}});
  const pref = (await (await page.request.get('/api/v1/learning/preferences')).json()).data;
  await page.request.put('/api/v1/learning/preferences', {data:{frameworkChoice:'UNDECIDED',expectedRevision:pref.revision}});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/');
  const panel = page.getByRole('region', {name:'我的下一步',exact:true});
  await expect(panel).toContainText('请选择框架方向');
  await panel.getByLabel('框架方向').focus();
  await expect(panel.getByLabel('框架方向')).toBeFocused();
  await panel.getByLabel('框架方向').selectOption('REACT');
  await panel.getByRole('button',{name:'保存方向',exact:true}).click();
  await expect(panel).toContainText('补齐基础 · JS-01');
  await page.reload(); await expect(panel.getByLabel('框架方向')).toHaveValue('REACT');
  for (const url of ['/plan','/knowledge/REACT-02','/knowledge/materials/react-02-component-boundaries-data-flow-composition.md/react-02']) {
    await page.goto(url); await expect(panel).toContainText('补齐基础 · JS-01');
  }
  await expect(page.getByLabel('练习合同状态')).toContainText('筛选后编辑器');
  await expect(page.locator('[data-reader-ready="true"]')).toBeVisible();
  await expect(page.getByText('同组下一篇 →',{exact:true})).toBeVisible();
  const reading = async () => (await (await page.request.get('/api/v1/knowledge/material-progress')).json()).data.find((r:{guide:string})=>r.guide==='react-02-component-boundaries-data-flow-composition.md');
  const before = await reading();
  await panel.getByLabel('框架方向').selectOption('VUE'); await panel.getByRole('button',{name:'保存方向',exact:true}).click();
  await expect(panel).toContainText('补齐基础 · WEB-01');
  const after = await reading(); expect(after?.progressPercent ?? 0).toBeGreaterThanOrEqual(before?.progressPercent ?? 0);
  await page.screenshot({path:join(evidence, 'reader-desktop.png'),fullPage:false,animations:'disabled'});
  // 补学链接与返回；查看不会开始目标。
  await panel.getByRole('link',{name:'补齐基础 · WEB-01 →',exact:true}).click();
  await expect(page.locator('.point-hero h1 code')).toHaveText('WEB-01');
  await page.goBack(); await expect(page.locator('[data-reader-ready="true"]')).toBeVisible();
  await page.request.post('/api/v1/learning/points/REACT-03/focus');
  await page.goto('/plan'); await expect(panel).toContainText('继续学习 · REACT-03'); await expect(panel).toContainText('位于其他方向');
  await page.screenshot({path:join(evidence, 'plan-desktop.png'),fullPage:false,animations:'disabled'});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:join(evidence, 'plan-narrow.png'),fullPage:false,animations:'disabled'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.request.post('/api/v1/learning/points/REACT-03/complete');
  await page.request.post('/api/v1/learning/points/WEB-01/defer',{data:{reason:'隔离测试'}});
  await page.reload(); await expect(panel).toContainText('所需基础已暂缓');
  await panel.locator('a[href="/knowledge/WEB-01"]').first().click();
  await page.getByRole('button',{name:'恢复学习',exact:true}).click();
  await expect(page.locator('.state-row')).not.toContainText('稍后再学');
  for (const code of ['VUE-01','VUE-02','VUE-03','VUE-04','VUE-05']) await page.request.post(`/api/v1/learning/points/${code}/complete`);
  await page.goto('/plan'); await expect(panel).toContainText('所选方向的已审学习链已完成');
  expect((await (await page.request.get('/api/v1/knowledge/recommendation')).json()).data.point).toBeNull();
  await page.screenshot({path:join(evidence, 'complete-narrow.png'),fullPage:false,animations:'disabled'});
  const dataDir = process.env.CAREER_ATLAS_E2E_DATA_DIR!;
  expect(dataDir).toContain('/tmp/e2e/career-atlas-e2e-');
  const requireServer = createRequire(new URL('../../server/package.json', import.meta.url));
  const Database = requireServer('better-sqlite3');
  const db = new Database(join(dataDir, 'career-atlas.db'));
  db.prepare("INSERT INTO learning_practice_attempts (id,knowledge_point_code,activity_id,submission_md,code,execution_output,status,created_at,updated_at) VALUES ('legacy-ui','REACT-02','strict-practice','旧夹具答卷：原文保留','旧代码','旧输出','DRAFT','old','old')").run();
  db.prepare("INSERT INTO assessment_sessions (id,knowledge_point_code,assessment_type,status,duration_minutes,created_at,updated_at) VALUES ('38107d0d-8a15-4f08-95ef-19144cdd8f00','REACT-02','FIRST','IN_PROGRESS',30,'2026-11-01','2026-11-01')").run();
  db.prepare("INSERT INTO assessment_questions (id,session_id,question_type,dimension,question_content,max_score,order_index,created_at) VALUES ('38107d0d-8a15-4f08-95ef-19144cdd8f01','38107d0d-8a15-4f08-95ef-19144cdd8f00','ESSAY','practice',?,20,0,'2026-11-01')").run(JSON.stringify({question:'旧题原文保留：解释原组件行为',sourceQuestion:'旧首考题 1'}));
  db.close();
  await page.goto('/knowledge/REACT-02');
  await page.getByRole('button', {name:'在系统中开始并完成 →'}).click();
  await page.getByText('历史练习 · framework-foundation-legacy · 只读证据',{exact:true}).click();
  const oldSubmission = page.getByText('旧夹具答卷：原文保留', { exact: true });
  await oldSubmission.scrollIntoViewIfNeeded();
  await expect(oldSubmission).toBeVisible();
  await page.screenshot({path:join(evidence, 'legacy-practice-narrow.png'),fullPage:false,animations:'disabled'});
  const legacy = (await (await page.request.get('/api/v1/assessments/38107d0d-8a15-4f08-95ef-19144cdd8f00')).json()).data;
  expect(JSON.stringify(legacy)).toContain('旧题原文保留');
  await page.goto('/assessment/38107d0d-8a15-4f08-95ef-19144cdd8f00');
  const oldQuestion = page.getByText('旧题原文保留：解释原组件行为', {exact:true});
  await oldQuestion.scrollIntoViewIfNeeded();
  await expect(oldQuestion).toBeVisible();
  await page.screenshot({path:join(evidence, 'legacy-challenge-narrow.png'),fullPage:false,animations:'disabled'});
  await writeFile(join(evidence, 'pages.json'),JSON.stringify({time:new Date().toISOString(),browser:browser.version(),viewports:[{width:1440,height:1000},{width:390,height:844}],baseURL:'http://127.0.0.1:42731',paths:['/','/plan','/knowledge/REACT-02','/knowledge/WEB-01','/assessment/38107d0d-8a15-4f08-95ef-19144cdd8f00','/knowledge/materials/react-02-component-boundaries-data-flow-composition.md/react-02'],checks:['选择刷新持久化','各入口下一步一致','切换保留焦点','阅读进度不清零','补学返回','暂缓恢复','链完成无兜底','键盘焦点','窄屏无横向溢出','旧练习只读','旧挑战原题读取']},null,2));
});

test('详情暂缓前置立即同步个人推荐并可恢复', async ({ page, browser }, testInfo) => {
  const evidence = testInfo.outputPath('evidence');
  await mkdir(evidence, { recursive: true });
  await page.request.post('/api/v1/import/reset-learning-progress', { data: {} });
  const preference = (await (await page.request.get('/api/v1/learning/preferences')).json()).data;
  await page.request.put('/api/v1/learning/preferences', { data: { frameworkChoice: 'REACT', expectedRevision: preference.revision } });
  await page.goto('/knowledge/REACT-02');
  const panel = page.getByRole('region', { name: '我的下一步', exact: true });
  await expect(panel).toContainText('补齐基础 · JS-01');
  await page.getByRole('button', { name: '暂缓此知识点', exact: true }).click();
  await expect(panel).toContainText('所需基础已暂缓');
  await expect(panel.locator('.next')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '暂缓此知识点', exact: true })).toHaveCount(0);
  const route = (await (await page.request.get('/api/v1/learning/route')).json()).data;
  expect(route.outcome).toBe('PAUSED_PREREQUISITE');
  expect(route.next).toBeNull();
  expect((await (await page.request.get('/api/v1/knowledge/recommendation')).json()).data.point).toBeNull();
  await panel.screenshot({ path: join(evidence, 'defer-detail-desktop.png'), animations: 'disabled' });
  await panel.locator('a[href="/knowledge/JS-01"]').first().click();
  await page.getByRole('button', { name: '恢复学习', exact: true }).click();
  await expect(panel).toContainText('补齐基础 · JS-01');
  await page.goBack();
  await expect(panel).toContainText('补齐基础 · JS-01');
  await expect(page.getByRole('button', { name: '暂缓此知识点', exact: true })).toBeVisible();
  await writeFile(join(evidence, 'defer-pages.json'), JSON.stringify({ time: new Date().toISOString(), browser: browser.version(), viewport: page.viewportSize(), url: page.url(), checks: ['详情暂缓立即显示 PAUSED_PREREQUISITE', '旧推荐与分支均无下一步', '恢复单点后返回推荐一致'] }, null, 2));
});
